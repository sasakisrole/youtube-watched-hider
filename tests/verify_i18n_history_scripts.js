function quotedEnd(s, start) {
  for (let i = start + 1; i < s.length; i++) {
    if (s[i] === '\\') { i++; continue; }
    if (s[start] === '\u0060' && s.slice(i, i + 2) === '\x24{') { i = balancedEnd(s, i + 1) - 1; continue; }
    if (s[i] === s[start]) return i + 1;
  }
  throw Error('Unclosed string');
}
function balancedEnd(s, start) {
  const close = { '(': ')', '[': ']', '{': '}' }[s[start]];
  for (let i = start + 1; i < s.length; i++) {
    if ("'\"\u0060".includes(s[i])) { i = quotedEnd(s, i) - 1; continue; }
    if ('([{'.includes(s[i])) { i = balancedEnd(s, i) - 1; continue; }
    if (s[i] === close) return i + 1;
  }
  throw Error('Unclosed expression');
}
function argumentsOf(s, open) {
  const end = balancedEnd(s, open), args = [];
  let start = open + 1;
  for (let i = start; i < end - 1; i++) {
    if ("'\"\u0060".includes(s[i])) { i = quotedEnd(s, i) - 1; continue; }
    if ('([{'.includes(s[i])) { i = balancedEnd(s, i) - 1; continue; }
    if (s[i] === ',') { args.push(s.slice(start, i).trim()); start = i + 1; }
  }
  args.push(s.slice(start, end - 1).trim());
  return { end, args };
}
